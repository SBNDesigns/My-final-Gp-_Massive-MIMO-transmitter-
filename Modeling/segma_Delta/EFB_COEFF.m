%% ----------------------------------------------------------------
%  الحل اليدوي والمضمون: تعديل الأصفار بمعامل "a"
%% ----------------------------------------------------------------

clear;
clc;

% --- معامل التعديل (Stability Factor) ---
% قيمة قريبة من 1. كلما كانت أصغر، كان النظام أكثر استقرارًا
% ولكن تشكيل الضوضاء أقل فعالية عند DC.
% ابدأ بقيمة مثل 0.99 أو 0.995.
a = 0.7660;

fprintf('--- الحل اليدوي باستخدام معامل التعديل a = %.4f ---\n', a);

% --- حساب معاملات NTF الجديد (1 - a*z^-1)^3 ---
n0 = 1;
n1 = -3 * a;
n2 = 3 * a^2;
n3 = -a^3;

fprintf('معاملات NTF الجديد (n0, n1, n2, n3):\n');
fprintf('%.8f, %.8f, %.8f, %.8f\n\n', n0, n1, n2, n3);

% --- حساب معاملات EFB الجديدة (c1, c2, c3) ---
c1 = -n1;
c2 = -n2;
c3 = -n3;

fprintf('--- المعاملات النهائية والمضمونة لهيكل EFB ---\n');
fprintf('c1 = %.8f\n', c1);
fprintf('c2 = %.8f\n', c2);
fprintf('c3 = %.8f\n', c3);

